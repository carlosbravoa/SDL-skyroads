// The glyph for a character, or the space glyph for anything out of range.
inline const std::array<uint8_t, DOS_FONT_HEIGHT>& dos_font_glyph(char ch) {
    const uint8_t c = static_cast<uint8_t>(ch);
    if (c < DOS_FONT_FIRST_CHAR || c > DOS_FONT_LAST_CHAR) return DOS_FONT_8X8[0];
    return DOS_FONT_8X8[c - DOS_FONT_FIRST_CHAR];
}

// Centred x for a string, exactly as the original computes it (@0x2c65-0x2c8a).
inline int32_t dos_text_centered_x(std::size_t length) {
    return 160 - static_cast<int32_t>(length * DOS_FONT_ADVANCE / 2);
}

